using System.Globalization;
using System.Text;
using Fabric.Core.Catalog;
using Fabric.Core.Choices;

namespace Fabric.Core.Reference;

/// <summary>
/// Writes the catalog as <c>docs/catalog.md</c>: every dimension and option, sorted by id, with its tier, rules, note and
/// the profiles whose resolved choices contain it. <c>\n</c> line ends and nothing from the machine or the clock, so the
/// same catalog always gives the same bytes.
/// </summary>
public static class CatalogReference
{
    private const string Header = """
        # Catalog reference

        Generated by `fabric reference` from `catalog/catalog.yaml`; do not edit it. A change to the catalog regenerates it:

        ```bash
        dotnet run --project src/Fabric.Cli -- reference --catalog catalog/catalog.yaml --output docs/catalog.md
        ```

        The grammar is in [catalog-rules.md](catalog-rules.md), the tiers in ADR-0003. A profile uses an option when its
        resolved choices contain it: set by the profile or one it extends, or taken as a default.

        """;

    private const string None = "—";

    public static string Write(CatalogModel catalog)
    {
        ArgumentNullException.ThrowIfNull(catalog);

        var resolved = ResolveProfiles(catalog);
        var text = new StringBuilder(Header.ReplaceLineEndings("\n"));

        text.Append("\n## Profiles\n\n| Profile | Extends |\n|---|---|\n");
        foreach (var profile in catalog.Profiles.Values.OrderBy(profile => profile.Id, StringComparer.Ordinal))
        {
            text.Append(CultureInfo.InvariantCulture, $"| {Code(profile.Id)} | {(profile.Extends is { } extends ? Code(extends) : None)} |\n");
        }

        text.Append("\n## Dimensions\n");
        foreach (var dimension in catalog.Dimensions.Values.OrderBy(dimension => dimension.Id, StringComparer.Ordinal))
        {
            WriteDimension(text, dimension, resolved);
        }

        return text.ToString();
    }

    /// <summary>Profile id to its complete choice set, project and module dimensions together.</summary>
    private static Dictionary<string, Dictionary<string, IReadOnlyList<string>>> ResolveProfiles(CatalogModel catalog)
    {
        Dictionary<string, Dictionary<string, IReadOnlyList<string>>> resolved = new(StringComparer.Ordinal);
        foreach (var profile in catalog.Profiles.Keys)
        {
            var resolution = ChoiceResolver.Resolve(catalog, profile, []);
            if (resolution.Choices is not { } choices)
            {
                throw new CatalogException($"profile '{profile}' does not resolve: {string.Join(" ", resolution.Errors)}");
            }

            resolved.Add(profile, new Dictionary<string, IReadOnlyList<string>>([.. choices.Project, .. choices.ModuleDefaults]));
        }

        return resolved;
    }

    private static void WriteDimension(
        StringBuilder text,
        Dimension dimension,
        Dictionary<string, Dictionary<string, IReadOnlyList<string>>> resolved)
    {
        text.Append(CultureInfo.InvariantCulture, $"\n### {Code(dimension.Id)}\n\n");
        var scope = dimension.Scope == DimensionScope.Project ? "project" : "module";
        text.Append(CultureInfo.InvariantCulture, $"- Scope: {scope}{(dimension.Multi ? ", multi-valued" : string.Empty)}\n");
        if (dimension.ActiveWhen is { } activeWhen)
        {
            text.Append(CultureInfo.InvariantCulture, $"- Active when: {Code(activeWhen.ToString())}\n");
        }

        text.Append(dimension switch
        {
            { DefaultFrom: { } followed } => $"- Default from: {Code(followed)}\n",
            { Default: null } => "- No default: set it whenever it is active.\n",
            { Default.Count: 0 } => "- Default: none (`[]`)\n",
            { Default: { } chosen } => $"- Default: {Codes(chosen)}\n",
        });

        if (dimension.Requires.Count > 0)
        {
            text.Append(CultureInfo.InvariantCulture, $"- Requires: {Conditions(dimension.Requires)}\n");
        }

        if (dimension.Note is { } note)
        {
            text.Append(CultureInfo.InvariantCulture, $"- Note: {Cell(note)}\n");
        }

        text.Append("\n| Option | Tier | Requires | Conflicts | Profiles | Note |\n|---|---|---|---|---|---|\n");
        var options = dimension.Options.Values.OrderBy(option => option.Id, StringComparer.Ordinal).ToList();
        foreach (var option in options)
        {
            var profiles = resolved
                .Where(profile => profile.Value.TryGetValue(dimension.Id, out var chosen) && chosen.Contains(option.Id))
                .Select(profile => profile.Key)
                .Order(StringComparer.Ordinal)
                .ToList();

            text.Append(
                CultureInfo.InvariantCulture,
                $"| {Code(option.Id)} | {(option.Tier == SupportTier.Supported ? "supported" : "experimental")} " +
                $"| {Conditions(option.Requires)} | {Conditions(option.Conflicts)} " +
                $"| {(profiles.Count == 0 ? None : Codes(profiles))} | {(option.Note is { } optionNote ? Cell(optionNote) : None)} |\n");
        }

        var settings = options.SelectMany(option => option.Settings.Values.Select(setting => (Option: option.Id, Setting: setting))).ToList();
        if (settings.Count == 0)
        {
            return;
        }

        text.Append("\nSettings:\n\n");
        foreach (var (option, setting) in settings)
        {
            text.Append(
                CultureInfo.InvariantCulture,
                $"- {Code($"{option}.{setting.Id}")}: default {SettingNumber.Format(setting.Default)}, " +
                $"from {SettingNumber.Format(setting.Minimum)} to {SettingNumber.Format(setting.Maximum)}." +
                $"{(setting.Note is { } settingNote ? $" {Cell(settingNote)}" : string.Empty)}\n");
        }
    }

    private static string Conditions(IReadOnlyList<Condition> conditions) =>
        conditions.Count == 0 ? None : string.Join(", ", conditions.Select(condition => Code(condition.ToString())));

    private static string Codes(IEnumerable<string> values) => string.Join(", ", values.Select(Code));

    private static string Code(string value) => $"`{value}`";

    /// <summary>
    /// Free text inside a table row or a list item: one line, a <c>|</c> that does not end the cell, and a <c>&lt;</c> that
    /// does not open an HTML tag (<c>Option&lt;T&gt;</c> would lose its <c>&lt;T&gt;</c>).
    /// </summary>
    private static string Cell(string value) => value
        .ReplaceLineEndings(" ")
        .Replace("|", "\\|", StringComparison.Ordinal)
        .Replace("<", "&lt;", StringComparison.Ordinal);
}
