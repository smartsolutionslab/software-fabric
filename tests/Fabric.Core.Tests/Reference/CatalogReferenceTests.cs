using Fabric.Core.Catalog;
using Fabric.Core.Reference;

namespace Fabric.Core.Tests.Reference;

/// <summary>
/// docs/catalog.md (M4-30): every dimension and option of the catalog, sorted by id, with its tier, rules, notes and the
/// profiles whose resolved choices contain it. Pinned byte for byte on a catalog small enough to read.
/// </summary>
public class CatalogReferenceTests
{
    private const string CatalogText = """
        version: 1
        profiles:
          small:
            module.style: crud
          everything:
            extends: small
            backend.database: sqlserver
            backend.search: [full-text]
        dimensions:
          module.style:
            scope: module
            default: ddd
            options:
              ddd:  { tier: supported, note: "AggregateRoot<TId> roots" }
              crud: { tier: experimental, note: "plain tables | no aggregates" }
          backend.database:
            scope: project
            default: postgres
            note: "One database per project."
            options:
              sqlserver: { tier: experimental, conflicts: ["backend.api-protocols has grpc"] }
              postgres:  { tier: supported }
          backend.api-protocols:
            scope: project
            multi: true
            default: [rest]
            requires: ["backend.api-protocols has rest"]
            options:
              rest: { tier: supported }
              grpc:
                tier: experimental
                requires: ["backend.database == postgres", "backend.api-protocols has rest"]
                settings:
                  deadline-seconds: { default: 30, minimum: 1, maximum: 300, note: "per call" }
                  retries: { default: 0.5, minimum: 0, maximum: 3 }
          backend.search:
            scope: project
            multi: true
            active-when: "backend.database == sqlserver"
            default: []
            options:
              full-text: { tier: experimental }
          backend.embeddings:
            scope: project
            active-when: "backend.database in (postgres)"
            default-from: backend.database
            options:
              postgres: { tier: experimental }
          backend.cache:
            scope: project
            active-when: "backend.api-protocols has grpc"
            options:
              redis: { tier: experimental }
        """;

    private const string Expected = """
        # Catalog reference

        Generated by `fabric reference` from `catalog/catalog.yaml`; do not edit it. A change to the catalog regenerates it:

        ```bash
        dotnet run --project src/Fabric.Cli -- reference --catalog catalog/catalog.yaml --output docs/catalog.md
        ```

        The grammar is in [catalog-rules.md](catalog-rules.md), the tiers in ADR-0003. A profile uses an option when its
        resolved choices contain it: set by the profile or one it extends, or taken as a default.

        ## Profiles

        | Profile | Extends |
        |---|---|
        | `everything` | `small` |
        | `small` | — |

        ## Dimensions

        ### `backend.api-protocols`

        - Scope: project, multi-valued
        - Default: `rest`
        - Requires: `backend.api-protocols has rest`

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `grpc` | experimental | `backend.database == postgres`, `backend.api-protocols has rest` | — | — | — |
        | `rest` | supported | — | — | `everything`, `small` | — |

        Settings:

        - `grpc.deadline-seconds`: default 30, from 1 to 300. per call
        - `grpc.retries`: default 0.5, from 0 to 3.

        ### `backend.cache`

        - Scope: project
        - Active when: `backend.api-protocols has grpc`
        - No default: set it whenever it is active.

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `redis` | experimental | — | — | — | — |

        ### `backend.database`

        - Scope: project
        - Default: `postgres`
        - Note: One database per project.

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `postgres` | supported | — | — | `small` | — |
        | `sqlserver` | experimental | — | `backend.api-protocols has grpc` | `everything` | — |

        ### `backend.embeddings`

        - Scope: project
        - Active when: `backend.database in (postgres)`
        - Default from: `backend.database`

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `postgres` | experimental | — | — | `small` | — |

        ### `backend.search`

        - Scope: project, multi-valued
        - Active when: `backend.database == sqlserver`
        - Default: none (`[]`)

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `full-text` | experimental | — | — | `everything` | — |

        ### `module.style`

        - Scope: module
        - Default: `ddd`

        | Option | Tier | Requires | Conflicts | Profiles | Note |
        |---|---|---|---|---|---|
        | `crud` | experimental | — | — | `everything`, `small` | plain tables \| no aggregates |
        | `ddd` | supported | — | — | — | AggregateRoot&lt;TId> roots |

        """;

    private static readonly CatalogModel Catalog = CatalogReader.Read(new StringReader(CatalogText), "catalog.yaml");

    [Fact]
    public void Writes_every_dimension_and_option_sorted_with_its_rules_notes_settings_and_the_profiles_that_use_it()
    {
        var markdown = CatalogReference.Write(Catalog);

        markdown.ShouldBe(Expected.ReplaceLineEndings("\n"));
    }

    [Fact]
    public void A_profile_the_catalog_cannot_resolve_is_reported_by_name_instead_of_listed_as_using_nothing()
    {
        var broken = CatalogReader.Read(
            new StringReader(CatalogText.Replace("module.style: crud", "module.style: crud\n    backend.cache: redis", StringComparison.Ordinal)),
            "catalog.yaml");

        var exception = Should.Throw<CatalogException>(() => CatalogReference.Write(broken));

        exception.Message.ShouldStartWith("profile 'small' does not resolve: ");
    }
}
